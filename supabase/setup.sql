-- Llegue: almacenamiento seguro de seguimiento para Supabase.
-- Ejecutar una sola vez desde Supabase > SQL Editor.

CREATE SCHEMA IF NOT EXISTS llegue_private;
CREATE SCHEMA IF NOT EXISTS llegue_api;
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;

CREATE TABLE IF NOT EXISTS llegue_private.tracking_deliveries (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  route_id text NOT NULL,
  stop_id text NOT NULL,
  public_token uuid NOT NULL DEFAULT gen_random_uuid(),
  update_token_hash bytea NOT NULL,
  snapshot jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL DEFAULT now() + interval '30 days',
  CONSTRAINT tracking_route_stop_unique UNIQUE (route_id, stop_id),
  CONSTRAINT tracking_public_token_unique UNIQUE (public_token),
  CONSTRAINT tracking_snapshot_object CHECK (jsonb_typeof(snapshot) = 'object')
);

CREATE TABLE IF NOT EXISTS llegue_private.tracking_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  delivery_id uuid NOT NULL
    REFERENCES llegue_private.tracking_deliveries(id) ON DELETE CASCADE,
  idempotency_key uuid NOT NULL UNIQUE,
  event_type text NOT NULL CHECK (event_type IN (
    'delivery.en_route',
    'delivery.completed',
    'delivery.failed',
    'delivery.eta_changed',
    'delivery.exception'
  )),
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  occurred_at timestamptz NOT NULL,
  received_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT tracking_payload_object CHECK (jsonb_typeof(payload) = 'object')
);

CREATE INDEX IF NOT EXISTS tracking_deliveries_expiry_idx
  ON llegue_private.tracking_deliveries (expires_at);

CREATE INDEX IF NOT EXISTS tracking_events_delivery_idx
  ON llegue_private.tracking_events (delivery_id, received_at DESC);

CREATE OR REPLACE FUNCTION llegue_private.register_tracking(
  p_route_id text,
  p_stop_id text,
  p_snapshot jsonb,
  p_update_token text DEFAULT NULL
) RETURNS TABLE (
  "publicToken" text,
  "updateToken" text,
  snapshot jsonb
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, extensions, llegue_private
AS $$
DECLARE
  current_row llegue_private.tracking_deliveries%ROWTYPE;
  generated_update_token text;
BEGIN
  IF length(trim(COALESCE(p_route_id, ''))) = 0
     OR length(trim(COALESCE(p_stop_id, ''))) = 0 THEN
    RAISE EXCEPTION 'routeId y stopId son obligatorios' USING ERRCODE = '22023';
  END IF;

  IF p_snapshot IS NULL OR jsonb_typeof(p_snapshot) <> 'object' THEN
    RAISE EXCEPTION 'snapshot debe ser un objeto JSON' USING ERRCODE = '22023';
  END IF;

  SELECT delivery.* INTO current_row
  FROM llegue_private.tracking_deliveries AS delivery
  WHERE delivery.route_id = p_route_id AND delivery.stop_id = p_stop_id
  FOR UPDATE;

  IF NOT FOUND THEN
    generated_update_token := replace(gen_random_uuid()::text, '-', '')
      || replace(gen_random_uuid()::text, '-', '');

    INSERT INTO llegue_private.tracking_deliveries (
      route_id, stop_id, update_token_hash, snapshot
    ) VALUES (
      p_route_id,
      p_stop_id,
      extensions.digest(generated_update_token, 'sha256'),
      p_snapshot
    )
    RETURNING
      tracking_deliveries.public_token::text,
      generated_update_token,
      tracking_deliveries.snapshot
    INTO "publicToken", "updateToken", snapshot;

    RETURN NEXT;
    RETURN;
  END IF;

  IF p_update_token IS NULL
     OR extensions.digest(p_update_token, 'sha256') <> current_row.update_token_hash THEN
    RAISE EXCEPTION 'capacidad de actualización inválida' USING ERRCODE = '42501';
  END IF;

  UPDATE llegue_private.tracking_deliveries AS delivery
  SET snapshot = p_snapshot,
      updated_at = now(),
      expires_at = now() + interval '30 days'
  WHERE delivery.id = current_row.id
  RETURNING
    delivery.public_token::text,
    NULL::text,
    delivery.snapshot
  INTO "publicToken", "updateToken", snapshot;

  RETURN NEXT;
END;
$$;

CREATE OR REPLACE FUNCTION llegue_private.apply_tracking_event(
  p_route_id text,
  p_stop_id text,
  p_update_token text,
  p_idempotency_key uuid,
  p_event_type text,
  p_occurred_at timestamptz,
  p_payload jsonb,
  p_snapshot jsonb
) RETURNS TABLE (
  accepted boolean,
  duplicate boolean,
  snapshot jsonb
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, extensions, llegue_private
AS $$
DECLARE
  current_row llegue_private.tracking_deliveries%ROWTYPE;
  next_status text;
BEGIN
  IF p_event_type NOT IN (
    'delivery.en_route',
    'delivery.completed',
    'delivery.failed',
    'delivery.eta_changed',
    'delivery.exception'
  ) THEN
    RAISE EXCEPTION 'tipo de evento no permitido' USING ERRCODE = '22023';
  END IF;

  SELECT delivery.* INTO current_row
  FROM llegue_private.tracking_deliveries AS delivery
  WHERE delivery.route_id = p_route_id AND delivery.stop_id = p_stop_id
  FOR UPDATE;

  IF NOT FOUND
     OR extensions.digest(COALESCE(p_update_token, ''), 'sha256')
        <> current_row.update_token_hash THEN
    RAISE EXCEPTION 'capacidad de actualización inválida' USING ERRCODE = '42501';
  END IF;

  IF EXISTS (
    SELECT 1 FROM llegue_private.tracking_events AS event
    WHERE event.idempotency_key = p_idempotency_key
  ) THEN
    accepted := true;
    duplicate := true;
    snapshot := current_row.snapshot;
    RETURN NEXT;
    RETURN;
  END IF;

  next_status := CASE p_event_type
    WHEN 'delivery.en_route' THEN 'en_camino'
    WHEN 'delivery.completed' THEN 'completada'
    WHEN 'delivery.failed' THEN 'no_entregada'
    ELSE COALESCE(p_snapshot->>'status', current_row.snapshot->>'status', 'pendiente')
  END;

  INSERT INTO llegue_private.tracking_events (
    delivery_id,
    idempotency_key,
    event_type,
    payload,
    occurred_at
  ) VALUES (
    current_row.id,
    p_idempotency_key,
    p_event_type,
    COALESCE(p_payload, '{}'::jsonb),
    p_occurred_at
  );

  UPDATE llegue_private.tracking_deliveries AS delivery
  SET snapshot = current_row.snapshot
      || COALESCE(p_snapshot, '{}'::jsonb)
      || jsonb_build_object('status', next_status, 'updatedAt', now()),
      updated_at = now(),
      expires_at = now() + interval '30 days'
  WHERE delivery.id = current_row.id
  RETURNING delivery.snapshot INTO snapshot;

  accepted := true;
  duplicate := false;
  RETURN NEXT;
END;
$$;

CREATE OR REPLACE FUNCTION llegue_private.get_public_tracking(
  p_public_token uuid
) RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, llegue_private
AS $$
  SELECT delivery.snapshot || jsonb_build_object('updatedAt', delivery.updated_at)
  FROM llegue_private.tracking_deliveries AS delivery
  WHERE delivery.public_token = p_public_token
    AND delivery.expires_at > now();
$$;

CREATE OR REPLACE FUNCTION llegue_private.purge_expired_tracking()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, llegue_private
AS $$
DECLARE
  deleted_count integer;
BEGIN
  DELETE FROM llegue_private.tracking_deliveries
  WHERE expires_at <= now();
  GET DIAGNOSTICS deleted_count = ROW_COUNT;
  RETURN deleted_count;
END;
$$;

